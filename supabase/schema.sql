create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text not null unique,
  display_name text,
  is_owner boolean not null default false,
  allow_owner_review boolean not null default false,
  privacy_ack_at timestamptz,
  created_at timestamptz not null default now(),
  last_seen_at timestamptz
);
create table if not exists public.chats (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references public.profiles(id) on delete cascade,
  title text not null default 'New medical chat' check (char_length(title)<=120),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create table if not exists public.ai_messages (
  id uuid primary key default gen_random_uuid(),
  chat_id uuid not null references public.chats(id) on delete cascade,
  user_id uuid not null references public.profiles(id) on delete cascade,
  role text not null check (role in ('user','assistant','system')),
  content text not null check (char_length(content)<=30000),
  selected_terms jsonb not null default '[]'::jsonb,
  created_at timestamptz not null default now(),
  edited_at timestamptz
);
create table if not exists public.user_events (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  event_type text not null check (char_length(event_type)<=80),
  metadata jsonb not null default '{}'::jsonb,
  user_agent text,
  created_at timestamptz not null default now()
);
create table if not exists public.term_translation_cache (
  term_id text not null,
  language text not null,
  definition text not null,
  explanation text,
  model text,
  reviewed boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  primary key(term_id,language)
);
create table if not exists public.ai_usage_daily (
  user_id uuid not null references public.profiles(id) on delete cascade,
  usage_day date not null default current_date,
  chat_count integer not null default 0,
  translation_count integer not null default 0,
  primary key(user_id,usage_day)
);

create or replace function public.handle_new_user() returns trigger
language plpgsql security definer set search_path=public as $$
declare v_review boolean := false; v_privacy boolean := false;
begin
  begin v_review := coalesce((new.raw_user_meta_data->>'allow_owner_review')::boolean,false); exception when others then v_review:=false; end;
  begin v_privacy := coalesce((new.raw_user_meta_data->>'privacy_accepted')::boolean,false); exception when others then v_privacy:=false; end;
  insert into public.profiles(id,email,allow_owner_review,privacy_ack_at,created_at)
  values(new.id,coalesce(new.email,''),v_review,case when v_privacy then now() else null end,now())
  on conflict(id) do update set email=excluded.email;
  return new;
end;$$;
drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users for each row execute procedure public.handle_new_user();

