create or replace function public.is_owner() returns boolean
language sql stable security definer set search_path=public as $$
 select exists(select 1 from public.profiles p where p.id=auth.uid() and p.is_owner=true)
$$;

-- Ordinary user data access: strictly self-only.
drop policy if exists "profile self read" on public.profiles;
create policy "profile self read" on public.profiles for select using (id=auth.uid());
drop policy if exists "chats own read" on public.chats;
create policy "chats own read" on public.chats for select using (user_id=auth.uid());
drop policy if exists "chats own insert" on public.chats;
create policy "chats own insert" on public.chats for insert with check (user_id=auth.uid());
drop policy if exists "chats own update" on public.chats;
create policy "chats own update" on public.chats for update using (user_id=auth.uid()) with check (user_id=auth.uid());
drop policy if exists "chats own delete" on public.chats;
create policy "chats own delete" on public.chats for delete using (user_id=auth.uid());
drop policy if exists "messages own read" on public.ai_messages;
create policy "messages own read" on public.ai_messages for select using (user_id=auth.uid());
drop policy if exists "messages edit own prompt" on public.ai_messages;
create policy "messages edit own prompt" on public.ai_messages for update using (user_id=auth.uid() and role='user' and exists(select 1 from public.chats c where c.id=chat_id and c.user_id=auth.uid())) with check (user_id=auth.uid() and role='user' and exists(select 1 from public.chats c where c.id=chat_id and c.user_id=auth.uid()));
drop policy if exists "events own insert" on public.user_events;
create policy "events own insert" on public.user_events for insert with check (user_id=auth.uid());
drop policy if exists "translation public read" on public.term_translation_cache;
create policy "translation public read" on public.term_translation_cache for select using (true);

create or replace function public.touch_last_seen() returns void
language sql security definer set search_path=public as $$
 update public.profiles set last_seen_at=now() where id=auth.uid()
$$;
create or replace function public.set_owner_review_consent(p_allow boolean) returns void
language plpgsql security definer set search_path=public as $$
begin
 if auth.uid() is null then raise exception 'Authentication required'; end if;
 update public.profiles set allow_owner_review=coalesce(p_allow,false),privacy_ack_at=coalesce(privacy_ack_at,now()) where id=auth.uid();
end;$$;

-- Owner analytics functions. Content audit requires the user's current opt-in.
create or replace function public.admin_dashboard_stats()
returns table(total_users bigint,total_chats bigint,total_messages bigint,total_events bigint)
language plpgsql security definer set search_path=public as $$
begin
 if not public.is_owner() then raise exception 'Owner access required'; end if;
 return query select (select count(*) from public.profiles),(select count(*) from public.chats),(select count(*) from public.ai_messages),(select count(*) from public.user_events);
end;$$;

create or replace function public.admin_user_summaries()
returns table(id uuid,email text,created_at timestamptz,last_seen_at timestamptz,is_owner boolean,allow_owner_review boolean,chat_count bigint,message_count bigint)
language plpgsql security definer set search_path=public as $$
begin
 if not public.is_owner() then raise exception 'Owner access required'; end if;
 return query select p.id,p.email,p.created_at,p.last_seen_at,p.is_owner,p.allow_owner_review,
  (select count(*) from public.chats c where c.user_id=p.id),
  (select count(*) from public.ai_messages m where m.user_id=p.id)
 from public.profiles p order by p.created_at desc;
end;$$;

create or replace function public.admin_recent_events(p_limit integer default 100)
returns table(id bigint,user_id uuid,event_type text,metadata jsonb,user_agent text,created_at timestamptz)
language plpgsql security definer set search_path=public as $$
begin
 if not public.is_owner() then raise exception 'Owner access required'; end if;
 return query select e.id,e.user_id,e.event_type,e.metadata,e.user_agent,e.created_at from public.user_events e order by e.created_at desc limit least(greatest(coalesce(p_limit,100),1),500);
end;$$;

create or replace function public.admin_user_chats(p_user uuid)
returns table(id uuid,title text,created_at timestamptz,updated_at timestamptz)
language plpgsql security definer set search_path=public as $$
begin
 if not public.is_owner() then raise exception 'Owner access required'; end if;
 if not exists(select 1 from public.profiles p where p.id=p_user and p.allow_owner_review=true) then return; end if;
 return query select c.id,c.title,c.created_at,c.updated_at from public.chats c where c.user_id=p_user order by c.updated_at desc;
end;$$;

create or replace function public.admin_chat_messages(p_chat uuid)
returns table(id uuid,role text,content text,selected_terms jsonb,created_at timestamptz,edited_at timestamptz)
language plpgsql security definer set search_path=public as $$
begin
 if not public.is_owner() then raise exception 'Owner access required'; end if;
 if not exists(select 1 from public.chats c join public.profiles p on p.id=c.user_id where c.id=p_chat and p.allow_owner_review=true) then return; end if;
 return query select m.id,m.role,m.content,m.selected_terms,m.created_at,m.edited_at from public.ai_messages m where m.chat_id=p_chat order by m.created_at;
end;$$;

create or replace function public.consume_ai_quota(p_user uuid,p_kind text,p_limit integer)
returns boolean language plpgsql security definer set search_path=public as $$
declare allowed boolean := false;
begin
 if p_user is null or p_limit < 1 or p_kind not in ('chat','translation') then return false; end if;
 insert into public.ai_usage_daily(user_id,usage_day) values(p_user,current_date) on conflict do nothing;
 if p_kind='chat' then
   update public.ai_usage_daily set chat_count=chat_count+1 where user_id=p_user and usage_day=current_date and chat_count < p_limit returning true into allowed;
 else
   update public.ai_usage_daily set translation_count=translation_count+1 where user_id=p_user and usage_day=current_date and translation_count < p_limit returning true into allowed;
 end if;
 return coalesce(allowed,false);
end;$$;

